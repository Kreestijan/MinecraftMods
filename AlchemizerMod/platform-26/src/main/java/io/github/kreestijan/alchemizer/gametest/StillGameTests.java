package io.github.kreestijan.alchemizer.gametest;

import io.github.kreestijan.alchemizer.Alchemizer;
import io.github.kreestijan.alchemizer.brewing.block.AlchemicalTubingBlock;
import io.github.kreestijan.alchemizer.brewing.blockentity.PressureChamberBlockEntity;
import io.github.kreestijan.alchemizer.registry.ModBlocks;
import java.util.function.Consumer;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.core.Holder;
import net.minecraft.core.registries.Registries;
import net.minecraft.gametest.framework.FunctionGameTestInstance;
import net.minecraft.gametest.framework.GameTestHelper;
import net.minecraft.gametest.framework.TestData;
import net.minecraft.gametest.framework.TestEnvironmentDefinition;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.Identifier;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.phys.shapes.VoxelShape;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.neoforge.event.RegisterGameTestsEvent;
import net.neoforged.neoforge.registries.DeferredHolder;
import net.neoforged.neoforge.registries.DeferredRegister;

/**
 * The in-game test for a still, run by {@code runGameTestServer}.
 *
 * <p>The unit tests in {@code core} drive {@code StillValidator} against a map of cells. That
 * proves the rules, and proves nothing at all about the parts that only exist in a world: that
 * {@code LevelStructureView} reads the right cells, that {@code ModTags} resolves to blocks a
 * player can actually place, and — the one thing no unit test can reach — that breaking a block
 * tells the chamber to think again. This test is the three of those together: it builds a still out
 * of real blocks, asks the block entity whether it formed, breaks a tank, and asks again.
 *
 * <p><b>Why a test function and not a test instance type.</b> There are two ways to register a game
 * test, and the choice is not cosmetic. A new {@code GameTestInstance} subclass would need a {@code
 * MapCodec} of its own registered in {@code test_instance_type}, because {@code test_instance} is a
 * synchronised registry: the server encodes every entry, built-in ones included, and sends them to
 * a connecting client. A codec that only ever threw would work right up until the first client
 * joined a server with tests enabled. A {@code FunctionGameTestInstance} is vanilla's own type with
 * vanilla's own codec, and the only thing it carries is a <em>name</em> — the body is looked up in
 * {@code test_function} when the test runs, on the server, where it is needed.
 *
 * <p><b>Why the functions are registered unconditionally.</b> {@code test_function} is a plain
 * built-in registry, so it is frozen long before any world loads, and the only window in which
 * anything can be added to it is mod construction. The two lambdas below therefore exist in the
 * shipped mod as well as in a development run. That is the price of the arrangement above and it is
 * a small one: they are unreachable, because the event that would give them a test to run is fired
 * only when the game is running tests.
 *
 * <p><b>Why the structure is {@code minecraft:empty}.</b> A test needs a template to be placed in,
 * and vanilla ships exactly one that is a single block of air. Building the still from code rather
 * than shipping a template means the shape under test is written next to the assertions about it,
 * where a reader can see both at once, and it means there is no binary file in the repository that
 * has to be regenerated by hand whenever the machine changes.
 */
public final class StillGameTests {

  /**
   * Test bodies, keyed by name.
   *
   * <p>Held here rather than in {@code registry/ModTags}-style constant classes because these are
   * not game content: nothing outside this package reads them, and nothing reads them at all except
   * the game test runner.
   */
  private static final DeferredRegister<Consumer<GameTestHelper>> TEST_FUNCTIONS =
      DeferredRegister.create(Registries.TEST_FUNCTION, Alchemizer.MOD_ID);

  private static final DeferredHolder<Consumer<GameTestHelper>, Consumer<GameTestHelper>>
      STILL_FORMS =
          TEST_FUNCTIONS.register(
              "still_forms_from_its_parts", () -> StillGameTests::stillFormsFromItsParts);

  private static final DeferredHolder<Consumer<GameTestHelper>, Consumer<GameTestHelper>>
      TUBING_CONNECTS =
          TEST_FUNCTIONS.register(
              "tubing_connects_to_its_neighbours",
              () -> StillGameTests::tubingConnectsToItsNeighbours);

  /** Vanilla's blank template — {@code data/minecraft/structure/empty.nbt}. */
  private static final Identifier EMPTY_STRUCTURE = Identifier.withDefaultNamespace("empty");

  /**
   * Enough ticks for the test to run at all. The body finishes in its first tick and says so, so
   * this is headroom rather than a budget.
   */
  private static final int MAX_TICKS = 100;

  /**
   * How long the framework waits after placing the template before calling the body. One tick is
   * the shortest non-zero value; the body places its own blocks, so there is nothing to wait for.
   */
  private static final int SETUP_TICKS = 1;

  private StillGameTests() {}

  /**
   * @param modEventBus the bus this mod's registration events arrive on
   */
  public static void register(IEventBus modEventBus) {
    TEST_FUNCTIONS.register(modEventBus);
  }

  /**
   * Gives the bodies above something to be run as.
   *
   * <p>Reached only when the game is running tests, which is what keeps this off the path of an
   * ordinary client or server.
   *
   * @param event the game test registries, open for this mod to add to
   */
  public static void onRegisterGameTests(RegisterGameTestsEvent event) {
    // The environment a test runs in — its game rules, weather and clock. A still cares about none
    // of them, so this is the empty one. Registered rather than looked up so that the test does not
    // depend on which environments vanilla happens to ship being present under a known name.
    Holder<TestEnvironmentDefinition<?>> environment =
        event.registerEnvironment(Identifier.fromNamespaceAndPath(Alchemizer.MOD_ID, "still"));

    event.registerTest(
        Identifier.fromNamespaceAndPath(Alchemizer.MOD_ID, "still_forms_from_its_parts"),
        new FunctionGameTestInstance(
            STILL_FORMS.getKey(),
            new TestData<>(environment, EMPTY_STRUCTURE, MAX_TICKS, SETUP_TICKS, true)));
    event.registerTest(
        Identifier.fromNamespaceAndPath(Alchemizer.MOD_ID, "tubing_connects_to_its_neighbours"),
        new FunctionGameTestInstance(
            TUBING_CONNECTS.getKey(),
            new TestData<>(environment, EMPTY_STRUCTURE, MAX_TICKS, SETUP_TICKS, true)));
  }

  /**
   * Builds a tier-1 still, checks it formed, breaks the tank holding it together, and checks it did
   * not.
   *
   * <p>The two tanks are the point of the second half. They are placed in a line, so the far one
   * reaches the pressure chamber only through the near one. Breaking the near tank therefore has to
   * drop the still to nothing even though a tank is still standing next to it — which is the case a
   * cache that only ever grew would get wrong.
   *
   * @param helper the running test's handle on its own copy of the world
   */
  private static void stillFormsFromItsParts(GameTestHelper helper) {
    // Positions are offsets from the corner of the test's template, not world coordinates. The
    // pressure chamber is at the origin of the machine because that is how the mod builds one: the
    // chamber's block entity is what asks the question, and it asks it about itself.
    BlockPos firebox = new BlockPos(0, 0, 0);
    BlockPos chamber = new BlockPos(0, 1, 0);
    BlockPos nearTank = new BlockPos(1, 1, 0);
    BlockPos farTank = new BlockPos(2, 1, 0);

    helper.setBlock(firebox, ModBlocks.IGNITION_CHAMBER.get());
    helper.setBlock(chamber, ModBlocks.PRESSURE_CHAMBER.get());
    helper.setBlock(nearTank, ModBlocks.ALCHEMICAL_TANK.get());
    helper.setBlock(farTank, ModBlocks.ALCHEMICAL_TANK.get());

    helper.assertBlockEntityData(
        chamber,
        PressureChamberBlockEntity.class,
        entity ->
            entity.still().isFormed()
                && entity.still().tier().tier() == 1
                && entity.connectedTanks().size() == 2,
        () ->
            Component.literal(
                "a firebox, a chamber on top of it and two tanks beside the chamber are a tier-1"
                    + " still"));

    helper.destroyBlock(nearTank);

    helper.assertBlockEntityData(
        chamber,
        PressureChamberBlockEntity.class,
        entity -> !entity.still().isFormed() && entity.connectedTanks().isEmpty(),
        () ->
            Component.literal(
                "breaking the tank the still was drawing through leaves it unformed, even though a"
                    + " tank is still standing next to the chamber"));

    helper.succeed();
  }

  /**
   * Places a tube between a chamber and a tank, checks the arms that should be there are there,
   * checks that the block is a 4-pixel pipe rather than a full cube, then breaks the tank and
   * checks that the arm goes with it.
   *
   * <p>The tube is placed first on purpose. The test helper sets a block's default state rather
   * than going through the item's placement path, so the arms are not computed by {@code
   * getStateForPlacement}; they arrive as the chamber and the tank are placed and the tube is asked
   * to update the side that changed. That is the path a player gets when a still is built in any
   * order, and it is the one worth testing.
   *
   * @param helper the running test's handle on its own copy of the world
   */
  private static void tubingConnectsToItsNeighbours(GameTestHelper helper) {
    BlockPos firebox = new BlockPos(0, 0, 0);
    BlockPos chamber = new BlockPos(0, 1, 0);
    BlockPos tubing = new BlockPos(1, 1, 0);
    BlockPos tank = new BlockPos(2, 1, 0);

    helper.setBlock(tubing, ModBlocks.ALCHEMICAL_TUBING.get());
    helper.setBlock(firebox, ModBlocks.IGNITION_CHAMBER.get());
    helper.setBlock(chamber, ModBlocks.PRESSURE_CHAMBER.get());
    helper.setBlock(tank, ModBlocks.ALCHEMICAL_TANK.get());

    helper.assertBlockState(
        tubing,
        state ->
            state.getValue(AlchemicalTubingBlock.WEST)
                && state.getValue(AlchemicalTubingBlock.EAST)
                && !state.getValue(AlchemicalTubingBlock.NORTH)
                && !state.getValue(AlchemicalTubingBlock.SOUTH)
                && !state.getValue(AlchemicalTubingBlock.UP)
                && !state.getValue(AlchemicalTubingBlock.DOWN),
        state ->
            Component.literal(
                "tubing between the chamber and a tank should grow an arm on each side and nowhere"
                    + " else: "
                    + state));

    BlockState state = helper.getBlockState(tubing);
    VoxelShape outline = state.getShape(helper.getLevel(), helper.absolutePos(tubing));
    helper.assertTrue(
        outline.min(Direction.Axis.Y) == 6.0 / 16.0 && outline.max(Direction.Axis.Y) == 10.0 / 16.0,
        Component.literal(
            "tubing's outline should be a 4-pixel pipe, not a full block: " + outline));

    VoxelShape collision = state.getCollisionShape(helper.getLevel(), helper.absolutePos(tubing));
    helper.assertTrue(
        collision.min(Direction.Axis.Y) == 6.0 / 16.0
            && collision.max(Direction.Axis.Y) == 10.0 / 16.0,
        Component.literal(
            "tubing's collision should be the pipe, not the whole block: " + collision));

    helper.destroyBlock(tank);

    helper.assertBlockState(
        tubing,
        stateAfter -> !stateAfter.getValue(AlchemicalTubingBlock.EAST),
        stateAfter ->
            Component.literal("breaking the tank should take the east arm with it: " + stateAfter));

    helper.succeed();
  }
}
